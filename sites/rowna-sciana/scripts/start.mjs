import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { spawn } from 'node:child_process';
const { values } = parseArgs({ options: { port: { type: 'string', default: '3000' } } });
if (!/^\d+$/.test(values.port) || Number(values.port) < 1 || Number(values.port) > 65535) throw new Error('Invalid port');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'dist/server.cjs');
if (!fs.existsSync(entry)) throw new Error('Run npm run build first');
const child = spawn(process.execPath, [entry], { cwd: root, stdio: 'inherit', env: { ...process.env, HOSTNAME: '127.0.0.1', PORT: values.port, CONTENT_DB_PATH: process.env.CONTENT_DB_PATH || path.join(root, 'data/content.sqlite') } });
for (const signal of ['SIGTERM', 'SIGINT']) process.on(signal, () => child.kill(signal));
child.on('exit', code => process.exit(code ?? 1));
